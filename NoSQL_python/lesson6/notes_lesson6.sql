-- MONGO DB
-- a document database
-- MongoDB community server is free to use
-- format of data is JSON (JavaScript Object Notation)

-- Example:
{
    "_id": "123",
    "name": "Hoodie Black",
    "price": 599,
    "tags": ["men", "clothes", "black"],
    "details": {"size": ["S", "M", "L", "XL"]}
}


-- WORDS TO KNOW
-- SQL  VS  Mongo DB
-- database -> database
-- table -> collection
-- row -> document
-- column -> field
-- primary key -> _id
-- JOIN -> Embedding or $lookup
-- SQL Query -> A filter (a python dictionary)


-- _id is a primary key
-- it is a unique identifier for each document
-- it is automatically generated by MongoDB

-- Example:
_id: ObjectId('670b2975972f3ad163eb9231')


--  mongodb://localhost:27017/
-- localhost is the server
-- 27017 is the port
-- / is the database

-- pymongo
from pymongo import MongoClient

client = MongoClient('mongodb://localhost:27017/') -- connect to the server
db = client['webshop'] -- connect to the database
products = db.products.find_one() -- find the first product (ask question to the database)
print(products) -- print the product

-- find and insert
products = db.products.find_one() -- find the first product (ask question to the database)
products = db.products.find_one({"_id": 1}) -- find the product with the id 1
products = db.products.find({"name": "Hoodie Black"}) -- find the product with the name "Hoodie Black"
product = db.products.count_documents({}) -- count how many

products = db.products.insert_one({}) -- insert a new product (add a new document to the collection)
products = db.products.insert_many([{}, {}, {}]) -- insert multiple products (add multiple documents to the collection)


